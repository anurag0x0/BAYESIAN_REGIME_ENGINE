
from pathlib import Path
import warnings

import joblib
import numpy as np
import pandas as pd
from statsmodels.tsa.api import VAR

warnings.filterwarnings("ignore")

# Project paths
ROOT = Path(__file__).resolve().parents[2]

FEATURES_PATH = ROOT / "data" / "processed" / "nifty50_features.csv"
REGIMES_PATH = ROOT / "data" / "processed" / "nifty50_regimes.csv"

MODEL_DIR = ROOT / "models" / "var"
REPORT_DIR = ROOT / "reports" / "var"

MODEL_DIR.mkdir(parents=True, exist_ok=True)
REPORT_DIR.mkdir(parents=True, exist_ok=True)

# Model configuration
VAR_FEATURES = [
    "daily_return",
    "volatility_20d",
    "momentum_5d",
    "daily_range",
]
MAX_LAGS = 5
TRAIN_RATIO = 0.80
MIN_ROWS = 30


def find_regime_column(df):
    """Identify the regime column generated by the HMM step."""
    candidates = [
        "regime",
        "hmm_regime",
        "hidden_state",
        "state",
    ]

    for col in candidates:
        if col in df.columns:
            return col

    # Fallback: detect a column with 'regime' or 'state' in its name
    for col in df.columns:
        name = col.lower()
        if "regime" in name or "state" in name:
            return col

    raise ValueError(
        "Could not identify HMM regime column in nifty50_regimes.csv. "
        f"Available columns: {list(df.columns)}"
    )


def load_and_merge_data():
    if not FEATURES_PATH.exists():
        raise FileNotFoundError(
            f"Feature file not found: {FEATURES_PATH}"
        )

    if not REGIMES_PATH.exists():
        raise FileNotFoundError(
            f"HMM output not found: {REGIMES_PATH}. "
            "Complete Step 5 first."
        )

    features = pd.read_csv(FEATURES_PATH, parse_dates=["date"])
    regimes = pd.read_csv(REGIMES_PATH, parse_dates=["date"])

    regime_col = find_regime_column(regimes)

    if regime_col != "regime":
        regimes = regimes.rename(columns={regime_col: "regime"})

    if "date" not in features.columns or "date" not in regimes.columns:
        raise ValueError("Both input files must contain a 'date' column.")

    # Keep only the required HMM date and regime label
    regimes = regimes[["date", "regime"]].drop_duplicates("date")

    df = features.merge(regimes, on="date", how="inner")
    df = df.sort_values("date").reset_index(drop=True)

    missing_features = [
        col for col in VAR_FEATURES if col not in df.columns
    ]
    if missing_features:
        raise ValueError(
            f"Missing VAR features: {missing_features}"
        )

    df = df.dropna(subset=VAR_FEATURES + ["regime"]).copy()

    if df.empty:
        raise ValueError("No usable rows after merging features and regimes.")

    return df


def fit_regime_var_models(df):
    # Chronological split; never shuffle time-series data
    split_index = int(len(df) * TRAIN_RATIO)
    train_df = df.iloc[:split_index].copy()

    models = {}
    summaries = []

    for regime in sorted(train_df["regime"].unique()):
        regime_df = train_df[train_df["regime"] == regime]
        values = regime_df[VAR_FEATURES].astype(float)

        print(f"\nTraining VAR for regime: {regime}")
        print(f"Training observations: {len(values)}")

        if len(values) < MIN_ROWS:
            print(
                f"Skipping regime {regime}: "
                f"requires at least {MIN_ROWS} rows."
            )
            continue

        # Limit lag count according to available observations
        max_lags = min(MAX_LAGS, max(1, len(values) // 10))

        try:
            var_model = VAR(values)
            fitted_model = var_model.fit(maxlags=max_lags, ic="aic")

            if fitted_model.k_ar < 1:
                print(f"Skipping regime {regime}: no valid VAR lag.")
                continue

            models[str(regime)] = fitted_model

            summaries.append({
                "regime": regime,
                "observations": len(values),
                "selected_lags": fitted_model.k_ar,
                "aic": fitted_model.aic,
                "bic": fitted_model.bic,
                "hqic": fitted_model.hqic,
            })

            print(f"Selected lags: {fitted_model.k_ar}")
            print(f"AIC: {fitted_model.aic:.6f}")
            print(f"BIC: {fitted_model.bic:.6f}")

        except Exception as exc:
            print(f"Could not fit regime {regime}: {exc}")

    if not models:
        raise RuntimeError(
            "No regime-specific VAR model could be trained. "
            "Check HMM labels and data volume."
        )

    return models, pd.DataFrame(summaries), split_index


def main():
    print("Loading feature and HMM regime data...")
    df = load_and_merge_data()

    print(f"Matched records: {len(df)}")
    print(f"Regimes found: {sorted(df['regime'].unique())}")

    models, summary_df, split_index = fit_regime_var_models(df)

    # Save trained regime-specific models
    model_path = MODEL_DIR / "regime_var_models.pkl"
    joblib.dump(models, model_path)

    # Save model summary
    summary_path = REPORT_DIR / "var_regime_summary.csv"
    summary_df.to_csv(summary_path, index=False)

    # Save run information
    info_path = REPORT_DIR / "var_run_info.txt"
    with open(info_path, "w", encoding="utf-8") as file:
        file.write("REGIME-SWITCHING VAR MODEL\n")
        file.write("==========================\n")
        file.write(f"Matched records: {len(df)}\n")
        file.write(f"Training records: {split_index}\n")
        file.write(f"Total regimes: {df['regime'].nunique()}\n")
        file.write(f"Models trained: {len(models)}\n")
        file.write(f"Features: {', '.join(VAR_FEATURES)}\n")
        file.write(f"Maximum lags: {MAX_LAGS}\n")
        file.write(
            "\nNote: This is an exploratory regime-specific VAR fit. "
            "It is not a live trading signal or a validated forecast. "
            "The HMM regime labels may be retrospective; use causal "
            "walk-forward regime inference for proper backtesting.\n"
        )

    print("\nRegime VAR training completed!")
    print(f"Models saved: {model_path}")
    print(f"Summary saved: {summary_path}")
    print(f"Run info saved: {info_path}")
    print("\nRegime model summary:")
    print(summary_df.to_string(index=False))


if __name__ == "__main__":
    main()
